package dev.conduit.simulator;

/** 测点类别，对应 V0.2-R spec 5.2 表中的生成规则；由 {@link PointClassifier} 判定。 */
public enum PointKind {
    /** 电压：220 附近小幅波动，三相略有差别。 */
    VOLTAGE,
    /** 电流、非光伏的有功/交流功率：按日用电曲线变化。 */
    LOAD,
    /** 光伏功率：6～18 点正弦日照 × 容量，夜间 0，叠加云层扰动。 */
    PV_POWER,
    /** 辐照度：同光伏功率，容量 1000 W/m²。 */
    IRRADIANCE,
    /** 累计量（电能、用水）：单调递增，增量与功率/流量相符。 */
    CUMULATIVE,
    /** 日累计（日发电量等）：同累计量，每天零点归零。 */
    DAILY_ENERGY,
    /** 温度：环境温度昼夜变化，设备温度随负载升高。 */
    TEMPERATURE,
    /** 流量：早晚用水高峰。 */
    FLOW,
    /** 水压、pH、浊度、余氯、湿度、PM2.5、CO₂、风速：合理范围内缓慢漂移。 */
    DRIFT,
    /** 枚举：多数时间为正常值，偶尔切换，同设备一小时内不变。 */
    ENUM,
    /** 布尔：多数为否，偶尔为是。 */
    BOOL,
    /** 其他数值：上下限内随机游走，无上下限时按单位推断范围。 */
    OTHER,
    /** 不生成（TEXT、无枚举项的 ENUM、未知类型）。 */
    SKIP
}
